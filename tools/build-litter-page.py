#!/usr/bin/env python3
"""Builds litter-backend/Page.html from the litter page (litter/index.html,
with assets/app.css, litter/litter.css and litter/litter.js put inline), so
the litter web app's own link serves the same page as the public site. Run it
after changing any of those files, before `clasp push`."""
import os
import re

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def read(*path):
    with open(os.path.join(root, *path), encoding='utf-8') as f:
        return f.read()


page = read('litter', 'index.html')
styles = '<style>\n' + read('assets', 'app.css') + '\n' + read('litter', 'litter.css') + '</style>'
page, n = re.subn(r'<link rel="stylesheet" href="\.\./assets/app\.css[^"]*">\n<link rel="stylesheet" href="litter\.css[^"]*">',
                  lambda m: styles, page)
assert n == 1, 'stylesheet links not found'
# Its icon has markup inside an attribute, which Apps Script refuses.
page, n = re.subn(r'<link rel="icon"[^\n]*\n', '', page)
assert n == 1, 'icon not found'
# config.js only matters on the public site.
page, n = re.subn(r'<script src="config\.js[^"]*"></script>\n', '', page)
assert n == 1, 'config.js not found'
script = read('litter', 'litter.js')
assert '</script' not in script
page, n = re.subn(r'<script src="litter\.js[^"]*"></script>', lambda m: '<script>\n' + script + '</script>', page)
assert n == 1, 'litter.js not found'
# The note goes after the doctype, so the page isn't read in quirks mode.
note = '<!-- Generated by tools/build-litter-page.py from litter/index.html, assets/app.css, litter/litter.css and litter/litter.js. Edit those, then rerun it. -->\n'
assert page.startswith('<!DOCTYPE html>\n')
page = page.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + note, 1)
with open(os.path.join(root, 'litter-backend', 'Page.html'), 'w', encoding='utf-8') as f:
    f.write(page)
print('litter-backend/Page.html:', len(page), 'characters')
